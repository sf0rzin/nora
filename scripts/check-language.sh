# ---------------------------------------------------------------------------
# Detection
# ---------------------------------------------------------------------------

# Alternation (not a bracket class) so the match is byte-sequence exact and does
# not depend on the locale grep happens to run under.
ACCENTS='á|à|â|ã|é|ê|í|ó|ô|õ|ú|ü|ç|Á|À|Â|Ã|É|Ê|Í|Ó|Ô|Õ|Ú|Ü|Ç'

# Portuguese words that essentially never occur in English source. Kept short on
# purpose. NOT included, because they are also English or common in identifiers:
# ate, pro, com, as, os, no, na, do, da, se, ou, e, a, o, um, ver, tem, sem.
WORDS='nao|sao|voce|entao|tambem|usuario|usuarios|configuracao|configuracoes|arquivo|arquivos|senha|senhas|reuniao|reunioes|transcricao|transcricoes|integracao|integracoes|atualizacao|mensagem|mensagens|para|que|uma|isso|esse|essa|pra|nenhum|nenhuma|servico|servicos|qualquer|porque|quando|porem|embora|apenas|ainda|agora|depois|antes|sobre|durante|atraves|muito|tudo'

violations=0

is_allowed() {
  local path=$1 entry
  for entry in "${ALLOWED[@]}"; do
    case "$path" in
      "$entry"*) return 0 ;;
    esac
  done
  return 1
}

# Build the candidate list once: every tracked file that is not allowlisted.
# The content scan below then runs grep TWICE IN TOTAL over that list, not twice
# per file — two process substitutions per file would open ~1400 descriptors on a
# repo this size and abort the run partway through, which under-reports silently.
candidates=()
while IFS= read -r file; do
  is_allowed "$file" && continue

  # Filenames and directory names must be English too.
  if printf '%s\n' "$file" | grep -qE "($ACCENTS)"; then
    printf '%s: Portuguese character in the file name\n' "$file"
    violations=$((violations + 1))
  elif printf '%s\n' "$file" | grep -qiE "(^|[^a-z])($WORDS)([^a-z]|$)"; then
    printf '%s: Portuguese word in the file name\n' "$file"
    violations=$((violations + 1))
  fi

  [ -f "$file" ] && candidates+=("$file")
done < <(git ls-files)

if [ "${#candidates[@]}" -gt 0 ]; then
  # `-I` skips binary files (fonts, icons, lockfile blobs). `-H` forces the
  # filename prefix even when a single file is left after allowlisting.
  findings=$(
    {
      printf '%s\0' "${candidates[@]}" |
        xargs -0 grep -nIHE "($ACCENTS)" -- 2>/dev/null |
        cut -d: -f1,2 | sed 's/$/: Portuguese character/' || true
      printf '%s\0' "${candidates[@]}" |
        xargs -0 grep -nIHiE "\b($WORDS)\b" -- 2>/dev/null |
        cut -d: -f1,2 | sed 's/$/: Portuguese word/' || true
    } | sort -u
  )

  if [ -n "$findings" ]; then
    printf '%s\n' "$findings"
    violations=$((violations + $(printf '%s\n' "$findings" | wc -l)))
  fi
fi

if [ "$violations" -gt 0 ]; then
  printf '\n%d Portuguese finding(s) outside the allowlist in scripts/check-language.sh.\n' "$violations" >&2
  printf 'Either translate the text, or add the path to the allowlist with an honest reason.\n' >&2
  exit 1
fi

printf 'OK — no Portuguese found outside the declared allowlist.\n'
