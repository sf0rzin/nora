#!/usr/bin/env bash
# Fails when Portuguese text appears outside the paths where pt-BR is allowed.
#
# The repository is normalised to English (filenames, identifiers, comments, docs,
# log messages, CI). Portuguese survives only in a small, declared set of places —
# the allowlist below. Everything else must be English.
#
# Two detection signals, both deliberately conservative (a missed word costs
# nothing; a false positive costs trust in the check):
#   (a) Portuguese-specific accented characters — high precision;
#   (b) a curated list of Portuguese words that essentially never appear in
#       English source. Words that are also English ("ate", "pro", "com", "as",
#       "no", "os") are excluded on purpose.
# File NAMES are checked with the same two signals.
#
# Exits non-zero listing every `file:line` (or `file: filename`) that violates.
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

